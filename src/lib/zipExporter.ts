import JSZip from "jszip";

export interface ComponentExportFiles {
  title: string;
  slug: string;
  reactCode: string;
  typescriptCode?: string;
  javascriptCode?: string;
  htmlCode?: string;
  cssCode?: string;
  jsCode?: string;
  vueCode?: string;
  svelteCode?: string;
  dependencies?: string[];
}

/**
 * Downloads a structured ZIP archive containing files for the component:
 * - TypeScript component (Component.tsx)
 * - React JavaScript component (Component.jsx)
 * - HTML, CSS, JS files (if available)
 * - README.md with installation & usage guidelines
 */
export async function downloadComponentZip(comp: ComponentExportFiles): Promise<void> {
  const zip = new JSZip();

  const folderName = `xui-${comp.slug}`;
  const root = zip.folder(folderName) || zip;

  // 1. React / Next.js folder (both TSX and JSX)
  const reactFolder = root.folder("react");
  if (reactFolder) {
    const tsCode = comp.typescriptCode || comp.reactCode;
    const jsCode = comp.javascriptCode || comp.reactCode;

    reactFolder.file(`${capitalize(comp.slug)}.tsx`, tsCode);
    reactFolder.file(`${capitalize(comp.slug)}.jsx`, jsCode);
  }

  // 2. Vanilla Web folder (HTML/CSS/JS)
  if (comp.htmlCode) {
    const vanillaFolder = root.folder("vanilla");
    if (vanillaFolder) {
      vanillaFolder.file("index.html", comp.htmlCode);
      if (comp.cssCode) vanillaFolder.file("styles.css", comp.cssCode);
      if (comp.jsCode) vanillaFolder.file("script.js", comp.jsCode);
    }
  }

  // 3. Vue folder
  if (comp.vueCode) {
    const vueFolder = root.folder("vue");
    if (vueFolder) {
      vueFolder.file(`${capitalize(comp.slug)}.vue`, comp.vueCode);
    }
  }

  // 4. Svelte folder
  if (comp.svelteCode) {
    const svelteFolder = root.folder("svelte");
    if (svelteFolder) {
      svelteFolder.file(`${capitalize(comp.slug)}.svelte`, comp.svelteCode);
    }
  }

  // 5. README.md
  const readmeContent = `# ${comp.title} - XUI Component

${comp.title} is a handcrafted animated UI component from **XUI** library.
Designed & curated by XUI.

## Required Dependencies:
\`\`\`bash
npm install ${comp.dependencies && comp.dependencies.length > 0 ? comp.dependencies.join(" ") : "motion lucide-react"}
\`\`\`

## React Usage:
\`\`\`tsx
import ${capitalize(comp.slug)} from './${capitalize(comp.slug)}';

export default function Example() {
  return <${capitalize(comp.slug)} />;
}
\`\`\`

## Vanilla HTML / CSS / JS Usage:
Simply include \`styles.css\` in the \`<head>\` and \`script.js\` at the end of \`<body>\`.

---
© XUI UI Platform - Built by XUI Team
`;

  root.file("README.md", readmeContent);

  // Generate blob & trigger browser download
  const blob = await zip.generateAsync({ type: "blob" });
  triggerDownload(blob, `${folderName}.zip`);
}

